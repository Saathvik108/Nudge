// Builds src/lib/seed-blob.ts: a gzipped+base64 copy of a freshly seeded
// SQLite database, embedded as a string so it ships inside the app bundle
// (no file tracing or external DB needed). Run via: npm run db:build-blob
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const root = process.cwd();
const dbPath = path.join(root, "prisma", "_seed_build.db");
const url = `file:${dbPath}`;

fs.rmSync(dbPath, { force: true });
fs.rmSync(dbPath + "-journal", { force: true });

console.log("→ creating schema in", dbPath);
execSync("npx prisma db push --skip-generate", {
  stdio: "inherit",
  env: { ...process.env, DATABASE_URL: url },
});

console.log("→ seeding");
execSync("npx tsx prisma/seed.ts", {
  stdio: "inherit",
  env: { ...process.env, DATABASE_URL: url },
});

console.log("→ packing");
const raw = fs.readFileSync(dbPath);
const gz = zlib.gzipSync(raw, { level: 9 });
const b64 = gz.toString("base64");

const out = `// AUTO-GENERATED by scripts/build-seed-blob.mjs — do not edit by hand.
// A gzipped + base64 pre-seeded SQLite database, unpacked at runtime by
// src/lib/db.ts so the app deploys with zero database setup.
export const SEED_DB_GZ_B64 = ${JSON.stringify(b64)};
`;
fs.writeFileSync(path.join(root, "src", "lib", "seed-blob.ts"), out);

fs.rmSync(dbPath, { force: true });
fs.rmSync(dbPath + "-journal", { force: true });

console.log(
  `✓ wrote src/lib/seed-blob.ts (db ${(raw.length / 1024).toFixed(0)}KB → ${(b64.length / 1024).toFixed(0)}KB base64)`,
);
